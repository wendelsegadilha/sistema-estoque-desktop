    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // montar objeto cliente
        var dao = new ProdutoDao();
        var fornDao = new FornecedorDao();
        var produto = new Produto();
        produto.setDescricao(txtDescricao.getText());
        produto.setPreco(Double.parseDouble(txtPreco.getText()));
        produto.setQuantidadeEstoque(Integer.parseInt(txtEstoque.getText()));
        var fornecedor = fornDao.buscarPorNome(cmbFornecedor.getSelectedItem().toString());
        produto.setFornecedor(fornecedor);
        // cadastrar objeto cliente
        dao.cadastrar(produto);
        // limpa o formulario
        Formularios.limparTela(pnlCadastro);
    }//GEN-LAST:event_btnSalvarActionPerformed

