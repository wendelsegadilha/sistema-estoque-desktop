    private void carregarDados(String filtro) {
        var dao = new ProdutoDao();
        List<Produto> produtos;
        
        if (filtro != null && !filtro.isEmpty()) {
            produtos = dao.filtarPorNome(filtro);
        } else {
            produtos = dao.listar();
        }
        
        DefaultTableModel dadosTabela = (DefaultTableModel)tblProdutos.getModel();
        dadosTabela.setNumRows(0);
        for (Produto produto : produtos) {
            dadosTabela.addRow(
                    new Object[] {
                        produto.getId(),
                        produto.getDescricao(),
                        produto.getPreco(),
                        produto.getQuantidadeEstoque(),
                        produto.getFornecedor().getNome()
                    }
            );
        } 
        
        FornecedorDao fornDao = new FornecedorDao();
        List<Fornecedor> fornecedores = fornDao.listar();
        for (Fornecedor fornecedor : fornecedores) {
            cmbFornecedor.addItem(fornecedor.getNome());
        }
    }
    
    public void pesquisarPorDescricao(String nome) {
        var dao = new ProdutoDao();
        var produto = dao.buscarPorNome(nome);
        
        if (produto == null) {
            JOptionPane.showMessageDialog(null, "Produto não encontrado");
            return;
        }
        
        txtCodigo.setText(String.valueOf(produto.getId()));
        txtDescricao.setText(produto.getDescricao());
        txtPreco.setText(String.valueOf(produto.getPreco()));
        txtEstoque.setText(String.valueOf(produto.getQuantidadeEstoque()));
        cmbFornecedor.setSelectedItem(produto.getFornecedor().getNome());
    }

